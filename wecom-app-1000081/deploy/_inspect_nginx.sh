#!/bin/bash
echo "=== nginx -v ==="
nginx -v 2>&1 || echo "NO_NGINX"
echo "=== nginx conf.d ==="
ls -la /etc/nginx/conf.d/ 2>/dev/null || echo "NO_CONF_D"
echo "=== nginx sites-enabled ==="
ls -la /etc/nginx/sites-enabled/ 2>/dev/null || echo "NO_SITES_ENABLED"
echo "=== nginx.conf http include ==="
grep -nE "include|sites-enabled|conf.d" /etc/nginx/nginx.conf 2>/dev/null
echo "=== existing server_name blocks ==="
grep -rn "server_name" /etc/nginx/conf.d/ /etc/nginx/sites-enabled/ 2>/dev/null || echo "NO_SERVER_NAME_FOUND"
echo "=== certbot? ==="
which certbot && certbot --version 2>&1 || echo "NO_CERTBOT"
echo "=== acme.sh? ==="
which acme.sh && acme.sh --version 2>&1 || echo "NO_ACME"
echo "=== port 80/443 listening? ==="
(ss -ltnp 2>/dev/null | grep -E ':80 |:443 ') || echo "NO_80_443_LISTENER"
echo "=== python3? ==="
which python3 && python3 --version || echo "NO_PY3"
echo "=== done ==="
